//! Software Fn-lock for ASUS USB keyboards that have none in hardware (GU605, 0b05:19b6).
//!
//! The keyboard sends F1-F12 without Fn and vendor usages with Fn. Fn-lock swaps the two with a
//! udev hwdb keymap, applied by the kernel to the evdev node (zero runtime cost, works before
//! login). Scancodes measured with evtest on a GU605MI; kernel 7.3 `hid-asus` usages.

/// USB product ids whose scancodes were measured.
pub const KNOWN_PRODUCTS: &[u16] = &[0x19b6];

pub const HWDB_FILE: &str = "/etc/udev/hwdb.d/90-tspmo-fnlock.hwdb";
pub const MARKER_ON: &str = "# tspmo fnlock=on";
pub const MARKER_OFF: &str = "# tspmo fnlock=off";

/// `(scancode, key with Fn-lock on, native key)`. Fn+F5 is consumed by the kernel (it cycles the
/// thermal mode) and Fn+F6/F9 send key combinations: they cannot be remapped.
const KEYS: &[(&str, &str, &str)] = &[
    ("7003a", "mute", "f1"),
    ("7003b", "kbdillumdown", "f2"),
    ("7003c", "kbdillumup", "f3"),
    ("7003d", "prog3", "f4"),
    ("7003e", "prog4", "f5"),
    ("7003f", "print", "f6"),
    ("70040", "brightnessdown", "f7"),
    ("70041", "brightnessup", "f8"),
    ("70042", "switchvideomode", "f9"),
    ("70043", "touchpad_toggle", "f10"),
    ("70044", "sleep", "f11"),
    ("c00e2", "f1", "mute"),
    ("ff3100c5", "f2", "kbdillumdown"),
    ("ff3100c4", "f3", "kbdillumup"),
    ("ff3100b3", "f4", "prog3"),
    ("ff310010", "f7", "brightnessdown"),
    ("ff310020", "f8", "brightnessup"),
    ("ff31006b", "f10", "f21"),
    ("ff31006c", "f11", "sleep"),
];

/// The hwdb file text. `on` swaps the rows; off restores the native keys explicitly, because
/// the kernel keeps a keymap until the device re-enumerates.
pub fn hwdb(product: u16, on: bool) -> String {
    let mut s = format!(
        "{}\n# generated by tspmod\nevdev:input:b0003v0B05p{product:04X}*\n",
        if on { MARKER_ON } else { MARKER_OFF }
    );
    for (code, locked, native) in KEYS {
        s.push_str(&format!(
            " KEYBOARD_KEY_{code}={}\n",
            if on { locked } else { native }
        ));
    }
    s
}

/// `Some(state)` if the file is ours.
pub fn parse_state(text: &str) -> Option<bool> {
    match text.lines().next()?.trim() {
        MARKER_ON => Some(true),
        MARKER_OFF => Some(false),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn layouts_swap_and_roundtrip() {
        let on = hwdb(0x19b6, true);
        let off = hwdb(0x19b6, false);
        assert!(on.contains("evdev:input:b0003v0B05p19B6*\n"));
        assert!(on.contains(" KEYBOARD_KEY_7003a=mute\n"));
        assert!(off.contains(" KEYBOARD_KEY_7003a=f1\n"));
        assert!(on.contains(" KEYBOARD_KEY_c00e2=f1\n"));
        assert_eq!(parse_state(&on), Some(true));
        assert_eq!(parse_state(&off), Some(false));
        assert_eq!(parse_state("junk"), None);
    }

    #[test]
    fn no_duplicate_scancodes() {
        let mut c: Vec<_> = KEYS.iter().map(|k| k.0).collect();
        c.sort();
        c.dedup();
        assert_eq!(c.len(), KEYS.len());
    }
}
